"""Check the numbers in data/README.md against the data, or regenerate them.

Run from the repo root, after manifest: python -m thinkguard.data.verify_readme [--write | --committed-only]
The block between the numbers markers is generated (Sources, Critique exclusions and Splits tables) from
data/interim/*.jsonl, data/manifests/ (read with manifest.load_split) and configs/data/sources.yaml; the prose around
it is hand-written and never touched.
Default: exits 1 with the first differing line if the README's block differs from the recomputed one; raises if a data
file is missing. --write: replaces the block with the recomputed one. --committed-only (CI, where data/interim does not
exist): exits 1 unless the Sources and Splits tables' rows, cut to their first two cells, are exactly each source's
name and revision from sources.yaml and each split's name and len(ids) in its manifest, in order.
"""

import argparse
import json
import sys
from collections import Counter
from itertools import zip_longest
from pathlib import Path

from thinkguard.data.audit import EXCLUSION_REASONS, TRAIN_FILTERED
from thinkguard.data.manifest import MANIFESTS, load_split
from thinkguard.data.normalize import GOLD_SPLIT, INTERIM, SOURCES
from thinkguard.data.schema import read_examples
from thinkguard.data.sources import TEST_SETS, load_sources

README = Path("data/README.md")
START, END = "<!-- numbers:start -->\n", "<!-- numbers:end -->"
RULES = "../protocol.md#training-data-filtering"
SPLITS = ("train", "validation", "smoke", "pilot", *(f"test_{name}" for name in TEST_SETS))  # Splits table order
WHY = {  # one line per exclusion_reason; a reason in the data with no line here raises KeyError
    "duplicate": "same `pair_hash` and targets as a row with a lower `raw_record_id`",
    "duplicate_conflict": "same `pair_hash` as a row with different targets",
    "teacher_human_conflict": "gold label or categories differ from the teacher's",
    **{f"test_overlap_{name}": f"shares its test key with a row of `{name}`" for name in TEST_SETS},
}


def row(*cells):
    return "| " + " | ".join(map(str, cells)) + " |"


def unsafe(examples):
    """Rows labeled unsafe: by teacher label for critique rows, by gold label for test-set rows."""
    labels = (e.teacher_safety_label if e.source_dataset == "critique" else e.gold_safety_label for e in examples)
    return sum(label == "unsafe" for label in labels)


def splits():
    """The split of every manifest in data/manifests/: SPLITS in that order, then any others by name."""
    order = {split: i for i, split in enumerate(SPLITS)}
    return sorted((p.stem for p in MANIFESTS.glob("*.json")), key=lambda split: (order.get(split, len(order)), split))


def block():
    """The generated block, recomputed from the data files."""
    sources = {s["name"]: s for s in load_sources()}
    lines = [
        "<!-- Generated by python -m thinkguard.data.verify_readme --write; do not edit by hand. -->",
        "",
        "### Sources",
        "",
        "| Source | Revision | Raw rows | Unsafe rows | Dropped by normalize | Final rows |",
        "|---|---|---|---|---|---|",
    ]
    for name in SOURCES:
        examples, raw = read_examples(INTERIM / f"{name}.jsonl"), sources[name]["rows"]
        revision = f"`{sources[name]['revision']}`"
        lines.append(row(f"`{name}`", revision, raw, unsafe(examples), raw - len(examples), len(examples)))
    lines += [
        "",
        (
            "Revision: the git commit each source is read at (`configs/data/sources.yaml`), which pins its contents."
            " `critique` is a commit of the ThinkGuard repo (luka-group/ThinkGuard); its gold labels come from"
            f" `{GOLD_SPLIT}` at `{sources[GOLD_SPLIT]['revision']}`. Unsafe rows count the final rows: teacher label"
            " for `critique`, gold label for the test sets."
        ),
    ]

    filtered = read_examples(TRAIN_FILTERED)
    reasons = Counter(e.exclusion_reason for e in filtered)
    lines += [
        "",
        "### Critique exclusions",
        "",
        (
            f"`{TRAIN_FILTERED.as_posix()}`: {reasons[None]} of {len(filtered)} rows kept. A row gets the first reason"
            " that matches, in this order."
        ),
        "",
        "| exclusion_reason | Rows | Rule |",
        "|---|---|---|",
        *(
            row(f"`{r}`", reasons[r], f"[{WHY[r]}]({RULES})")
            for r in (*EXCLUSION_REASONS, *sorted(set(reasons) - {None, *EXCLUSION_REASONS}))
        ),
    ]

    lines += [
        "",
        "### Splits",
        "",
        (
            "One manifest each in `data/manifests/`. Unsafe rows: teacher label for train, validation, smoke and"
            " pilot; gold label for the test splits."
        ),
        "",
        "| Split | Rows | Unsafe rows |",
        "|---|---|---|",
    ]
    for split in splits():
        examples = load_split(split)
        lines.append(row(f"`{split}`", len(examples), unsafe(examples)))
    return "\n".join(lines) + "\n"


def committed_rows():
    """{table: its expected rows cut to two cells}: each source's name and revision, each split's name and len(ids)."""
    sources = {s["name"]: s for s in load_sources()}
    tables = {"Sources": [row(f"`{name}`", f"`{sources[name]['revision']}`") for name in SOURCES], "Splits": []}
    for split in splits():
        with open(MANIFESTS / f"{split}.json", encoding="utf-8") as f:
            tables["Splits"].append(row(f"`{split}`", len(json.load(f)["ids"])))
    return tables


def table_rows(text, heading):
    """The data rows of the table under '### heading' in text, cut to their first two cells; [] if there is none."""
    lines = text.partition(f"### {heading}\n")[2].partition("\n### ")[0].splitlines()
    cells = [[c.strip() for c in line.strip("|").split("|")] for line in lines if line.startswith("|")]
    return [row(*c[:2]) for c in cells[2:]]  # skip the header and separator rows


def read_readme():
    """(text before the block, the block, text after it)."""
    with open(README, encoding="utf-8") as f:
        head, rest = f.read().split(START, 1)
    current, tail = rest.split(END, 1)
    return head, current, tail


def main():
    parser = argparse.ArgumentParser(description="Check or regenerate the numbers block of data/README.md.")
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--write", action="store_true", help="regenerate the block in place")
    mode.add_argument("--committed-only", action="store_true", help="check only revisions and split rows (CI)")
    args = parser.parse_args()
    head, current, tail = read_readme()

    if args.committed_only:
        for heading, expected in committed_rows().items():
            for i, (want, have) in enumerate(zip_longest(expected, table_rows(current, heading)), 1):
                if want != have:
                    sys.exit(f"FAIL: data/README.md {heading} table, row {i}:\n  README:   {have}\n  expected: {want}")
        print("data/README.md: source revisions and split rows match")
        return

    new = block()
    if args.write:
        with open(README, "w", encoding="utf-8", newline="\n") as f:
            f.write(head + START + new + END + tail)
        print(new, end="")
        return
    first = head.count("\n") + 2  # the README line number of the block's first line
    for i, (want, have) in enumerate(zip_longest(new.splitlines(), current.splitlines()), first):
        if want != have:
            sys.exit(f"FAIL: data/README.md line {i} differs from the data:\n  README:   {have}\n  expected: {want}")
    print("data/README.md: numbers match the data")


if __name__ == "__main__":
    main()
